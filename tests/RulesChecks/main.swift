import Foundation

func check(_ value: @autoclosure () -> Bool,_ message:String) {
    if !value() { fatalError(message) }
}
var calendar = Calendar(identifier:.gregorian)
calendar.timeZone = TimeZone(secondsFromGMT:0)!
let day = Date(timeIntervalSince1970:1_800_043_200)
func entry(_ offset:Int,_ note:String = "",_ mission:Int? = nil) -> EcoEntry {
    EcoEntry(date:day.addingTimeInterval(Double(offset)*86400),mood:.calma,note:note,missionID:mission,photo:nil,presenceConfirmed:false)
}
var place = EcoPlace(name:"Piazza",createdAt:day,coordinate:nil,seed:3,entries:[entry(0)])
check(EcoRules.progress(place,calendar:calendar).score == 1,"Birth must start as a seed")
place.entries.append(entry(0,"Un dettaglio nuovo",0))
let first = EcoRules.progress(place,calendar:calendar)
check(first.familiarity == 1 && first.memories == 1 && first.curiosity == 1 && first.stage == 1,"Distinct growth dimensions")
place.entries.append(entry(0,"Altro ricordo",0))
check(EcoRules.progress(place,calendar:calendar).score == first.score,"Repeated same-day memories and mission must not farm points")
check(!EcoRules.canComplete(place,now:day,calendar:calendar),"One mission per day")
place.entries.append(entry(1,"Un altro giorno",1))
let second = EcoRules.progress(place,calendar:calendar)
check(second.familiarity == 2 && second.memories == 2 && second.curiosity == 2,"New days and new mission count")
let mission = EcoRules.mission(place,now:day,calendar:calendar)
check(mission.id == EcoRules.mission(place,now:day,calendar:calendar).id,"Mission must be stable within the day")
check(mission.id != EcoRules.mission(place,now:day.addingTimeInterval(86400),calendar:calendar).id,"Mission should rotate next day")
let score = second.score
check(EcoRules.sleeping(place,now:day.addingTimeInterval(10*86400)),"Absence should trigger sleeping")
check(EcoRules.progress(place,calendar:calendar).score == score,"Sleeping must not remove progress")
check(!EcoCoordinate(latitude:91,longitude:0,accuracy:5,measuredAt:day).valid,"Reject invalid latitude")
check(!EcoCoordinate(latitude:0,longitude:0,accuracy:-1,measuredAt:day).valid,"Reject unavailable accuracy")
let encoded = try JSONEncoder().encode(EcoArchive(places:[place]))
let decoded = try JSONDecoder().decode(EcoArchive.self,from:encoded)
check(decoded.places[0].id == place.id && decoded.places[0].entries.count == place.entries.count,"JSON round trip must preserve history")
let folder = FileManager.default.temporaryDirectory.appendingPathComponent("eco-tests-\(UUID().uuidString)")
try FileManager.default.createDirectory(at:folder,withIntermediateDirectories:true)
defer { try? FileManager.default.removeItem(at:folder) }
let url = folder.appendingPathComponent("archive.json")
let store = EcoStore(fileURL:url)
let id = store.addPlace(name:"Il mio luogo",mood:.energia,coordinate:nil)!
check(!store.record(id:id,mood:.calma,note:"",photo:nil,missionID:nil,presence:false),"Repeated empty visit should be rejected")
check(store.record(id:id,mood:.curiosita,note:"Un ricordo scritto",photo:nil,missionID:nil,presence:false),"Memory should persist")
let reloaded = EcoStore(fileURL:url)
check(reloaded.places.count == 1 && reloaded.places[0].entries.count == 2,"Persist after relaunch")
check(store.addPlace(name:"Secondo",mood:.calma,coordinate:nil) != nil,"Second place")
check(store.addPlace(name:"Terzo",mood:.calma,coordinate:nil) != nil,"Third place")
check(store.addPlace(name:"Quarto",mood:.calma,coordinate:nil) == nil,"Three-place cap")
let before = try Data(contentsOf:url)
let bad = folder.appendingPathComponent("bad.json")
try Data("invalid JSON".utf8).write(to:bad)
check(!store.importBackup(bad),"Corrupt import should fail")
let afterBadImport = try Data(contentsOf:url)
check(afterBadImport == before,"Corrupt import must not overwrite existing file")
let broken = EcoStore(fileURL:bad)
check(broken.readOnly,"Corrupt archive should be protected")
check(broken.addPlace(name:"Do not overwrite",mood:.calma,coordinate:nil) == nil,"Protected file cannot be overwritten")
let protectedBytes = try Data(contentsOf:bad)
check(String(data:protectedBytes,encoding:.utf8) == "invalid JSON","Original corrupt bytes preserved")
let good = folder.appendingPathComponent("good.json")
try encoded.write(to:good)
check(store.importBackup(good),"Valid backup should restore")
check(store.places.first?.id == place.id,"Restore original identity")
store.erase()
check(store.places.isEmpty && !FileManager.default.fileExists(atPath:url.path),"Erase should remove history")
print("PASS: daily growth caps, mission rotation, sleeping, coordinates, JSON, persistence, three-place cap, protected corruption and backup restore")
